"""Machine-generated text from phone media (03 section 8.3, M-3).

On request, a photo's text is read (OCR, by the Tesseract program on this server) or an audio file is transcribed
(Whisper, from a model file already on this server). The result is stored in ``phone_derived_texts`` with the model
and its version, it is searchable as its own group ("Machine-generated text"), and it is always shown with the
label ``label()`` beside the original. The original file is never changed.

Nothing here makes a network request. The work runs in a child process with a memory cap and a time limit; the
child refuses every outbound connection before it loads anything, and a transcription model that is not already on
disk is refused with words, never downloaded.
"""
from __future__ import annotations

import json
import logging
import os
import subprocess
import sys
import tempfile
import uuid
from pathlib import Path

from sqlalchemy import text

from services.phone import fold as F

log = logging.getLogger(__name__)

KINDS = {"ocr": "Read text in this image", "transcript": "Transcribe this audio"}
OCR_CATEGORIES = {"Image"}
TRANSCRIPT_CATEGORIES = {"Audio", "Video"}
MAX_ATTEMPTS = 2
TIMEOUT_SECONDS = {"ocr": 300, "transcript": 3 * 3600}
# a running reading whose worker stopped (restart, crash) is taken up again once its kind's time limit has passed
# with a margin: an image after 15 minutes, not after the three hours a transcript may take
STALE_MARGIN_SECONDS = 600
STALE_SECONDS = {k: v + STALE_MARGIN_SECONDS for k, v in TIMEOUT_SECONDS.items()}
IDLE_SECONDS = 5
NO_MODEL = ("The transcription model is not installed on this server, so this audio cannot be transcribed here. "
            "Nothing was sent anywhere.")
NO_OCR = "The text reader (Tesseract) is not installed on this server. Nothing was sent anywhere."
STOPPED = "Reading this file stopped twice; it may be too large or damaged. The original is unchanged."


class DeriveError(ValueError):
    pass


def whisper_model_path() -> Path:
    return Path(os.environ.get("LOUPE_WHISPER_MODEL_PATH") or Path.home() / ".cache" / "whisper" / "base.pt")


def label(model, version, finished_at) -> str:
    from services.phone import time_display as T
    when = T.format_day_header(T.day_of(finished_at, "UTC")) if finished_at is not None else "an unknown date"
    return "Machine-generated by %s %s on %s. The original is above." % (model or "a model", version or "", when)


def _out(r) -> dict:
    d = dict(r._mapping)
    out = {"id": str(d["id"]), "file_uid": str(d["file_uid"]), "kind": d["kind"], "state": d["state"],
           "text": d["text"], "model": d["model"], "model_version": d["model_version"],
           "segments": d["segments"] or [], "error": d["error"],
           "created_at": d["created_at"].isoformat() if d["created_at"] else None,
           "finished_at": d["finished_at"].isoformat() if d["finished_at"] else None,
           "machine_generated": True}
    out["label"] = label(d["model"], d["model_version"], d["finished_at"]) if d["state"] == "done" else None
    return out


def request(conn, case_id, file_uid, kind, user_id=None) -> dict:
    """Queue a reading of one file. A reading already queued or running for the same file and kind is returned
    instead of a second one."""
    if kind not in KINDS:
        raise DeriveError("Choose a photo to read or an audio file to transcribe.")
    f = conn.execute(text("SELECT extraction_id, category, verification FROM pv_file WHERE case_id = :c AND "
                          "file_uid::text = :u"), {"c": str(case_id), "u": str(file_uid)}).first()
    if f is None:
        raise LookupError("This file is not in this case.")
    allowed = OCR_CATEGORIES if kind == "ocr" else TRANSCRIPT_CATEGORIES
    if (f.category or "") not in allowed:
        raise DeriveError("Text can be read only from photos, and transcripts made only from audio or video."
                          if kind == "ocr" else "Only audio or video can be transcribed.")
    if f.verification == "missing":
        from services.phone.media import MISSING_WORDS
        raise DeriveError(MISSING_WORDS)
    # one open reading per file and kind (unique partial index): a second request at the same moment inserts
    # nothing and gets the reading already open
    r = conn.execute(text(
        "INSERT INTO phone_derived_texts (id, case_id, extraction_id, file_uid, kind, created_by_user_id) VALUES "
        "(:i, :c, :e, :u, :k, :by) ON CONFLICT (case_id, file_uid, kind) WHERE state IN ('queued', 'running') "
        "DO NOTHING RETURNING *"),
        {"i": uuid.uuid4(), "c": str(case_id), "e": f.extraction_id, "u": str(file_uid), "k": kind,
         "by": str(user_id) if user_id else None}).first()
    if r is None:
        r = conn.execute(text("SELECT * FROM phone_derived_texts WHERE case_id = :c AND file_uid = :u AND kind = :k "
                              "AND state IN ('queued', 'running') ORDER BY created_at LIMIT 1"),
                         {"c": str(case_id), "u": str(file_uid), "k": kind}).first()
    return _out(r)


def list_for(conn, case_id, file_uid) -> list:
    return [_out(r) for r in conn.execute(text(
        "SELECT * FROM phone_derived_texts WHERE case_id = :c AND file_uid::text = :u ORDER BY created_at DESC"),
        {"c": str(case_id), "u": str(file_uid)})]


# ---- the work ------------------------------------------------------------------------------------------------------

# run first in every child: no connection can leave the process, whatever a library tries
GUARD = r'''
import socket
def _refuse(*a, **k):
    raise OSError("outbound connections are refused while reading evidence")
socket.socket.connect = _refuse
socket.socket.connect_ex = _refuse
socket.create_connection = _refuse
'''
_CHILD = GUARD + r'''
import json, os, resource, sys
mb = int(os.environ.get("LOUPE_PHONE_DERIVE_MEMORY_MB", "6144"))
resource.setrlimit(resource.RLIMIT_AS, (mb * 1024 * 1024, mb * 1024 * 1024))
kind, path, model = sys.argv[1], sys.argv[2], sys.argv[3]
if kind == "transcript":
    import whisper
    m = whisper.load_model(model, device="cpu", download_root=os.path.dirname(model))
    r = m.transcribe(path, fp16=False, verbose=None)
    seg = [{"start": round(float(s["start"]), 2), "end": round(float(s["end"]), 2), "text": s["text"].strip()}
           for s in r.get("segments", [])]
    v = getattr(whisper, "__version__", "")
    print(json.dumps({"text": (r.get("text") or "").strip(), "segments": seg, "language": r.get("language"),
                      "model": "Whisper", "version": ("base " + v).strip()}))
'''


def _tesseract_version():
    try:
        out = subprocess.run(["tesseract", "--version"], capture_output=True, text=True, timeout=30)
    except (OSError, subprocess.TimeoutExpired):
        return None
    first = (out.stdout or out.stderr or "").strip().splitlines()
    return first[0].split()[-1] if first else None


def _ocr(path):
    version = _tesseract_version()
    if version is None:
        raise DeriveError(NO_OCR)
    import resource

    def cap():
        mb = int(os.environ.get("LOUPE_PHONE_DERIVE_MEMORY_MB", "6144"))
        resource.setrlimit(resource.RLIMIT_AS, (mb * 1024 * 1024, mb * 1024 * 1024))
    r = subprocess.run(["tesseract", str(path), "stdout"], capture_output=True, text=True,
                       timeout=TIMEOUT_SECONDS["ocr"], preexec_fn=cap, env={"PATH": os.environ.get("PATH", ""),
                                                                            "OMP_THREAD_LIMIT": "1"})
    if r.returncode != 0:
        raise DeriveError("The text reader could not read this image. The original is unchanged.")
    return {"text": r.stdout.strip(), "segments": [], "model": "Tesseract", "version": version}


def _transcribe(path):
    model = whisper_model_path()
    if not model.is_file():
        raise DeriveError(NO_MODEL)
    env = {k: v for k, v in os.environ.items() if k in ("PATH", "HOME", "LOUPE_PHONE_DERIVE_MEMORY_MB")}
    env.update({"HF_HUB_OFFLINE": "1", "OMP_NUM_THREADS": "2"})
    r = subprocess.run([sys.executable, "-I", "-c", _CHILD, "transcript", str(path), str(model)],
                       capture_output=True, text=True, timeout=TIMEOUT_SECONDS["transcript"], env=env)
    if r.returncode != 0:
        if "No module named 'whisper'" in (r.stderr or ""):
            raise DeriveError(NO_MODEL)
        raise DeriveError("This audio could not be transcribed. The original is unchanged.")
    return json.loads(r.stdout.strip().splitlines()[-1])


def read_file(conn, case_id, file_uid, kind) -> dict:
    """Copy the file's bytes to a private temporary file, read it in a child process, delete the copy."""
    from services.phone import media
    name, _size, opener = media.content(conn, case_id, file_uid)
    suffix = Path(name).suffix[:10]
    with tempfile.TemporaryDirectory(prefix="loupe-derive-") as d:
        path = Path(d) / ("file" + suffix)
        with opener() as src, open(path, "wb") as dst:
            while True:
                chunk = src.read(1 << 20)
                if not chunk:
                    break
                dst.write(chunk)
        return _ocr(path) if kind == "ocr" else _transcribe(path)


def _claim(engine):
    while True:
        with engine.begin() as c:
            r = c.execute(text(
                "SELECT id, state, attempts FROM phone_derived_texts WHERE state = 'queued' OR (state = 'running' AND "
                "started_at < now() - make_interval(secs => CASE kind WHEN 'ocr' THEN :so ELSE :st END)) "
                "ORDER BY created_at FOR UPDATE SKIP LOCKED LIMIT 1"),
                {"so": STALE_SECONDS["ocr"], "st": STALE_SECONDS["transcript"]}).one_or_none()
            if r is None:
                return None
            if r.state == "running" and r.attempts >= MAX_ATTEMPTS:
                c.execute(text("UPDATE phone_derived_texts SET state = 'failed', error = :e, finished_at = now() "
                               "WHERE id = :i"), {"e": STOPPED, "i": r.id})
                continue
            return c.execute(text(
                "UPDATE phone_derived_texts SET state = 'running', started_at = clock_timestamp(), error = NULL, "
                "attempts = attempts + 1 WHERE id = :i RETURNING id, case_id, file_uid, kind, started_at"),
                {"i": r.id}).first()


def run_pending(engine, limit=1) -> list:
    done = []
    for _ in range(limit):
        job = _claim(engine)
        if job is None:
            break
        guard = {"i": job.id, "t": job.started_at}
        try:
            with engine.connect() as c:
                got = read_file(c, job.case_id, job.file_uid, job.kind)
            body = got.get("text") or ""
            with engine.begin() as c:
                c.execute(text(
                    "UPDATE phone_derived_texts SET state = 'done', text = :x, text_folded = :f, model = :m, "
                    "model_version = :v, segments = CAST(:s AS jsonb), finished_at = now() WHERE id = :i AND "
                    "state = 'running' AND started_at = :t"),
                    dict(guard, x=body, f=F.fold(body), m=got["model"], v=got["version"],
                         s=json.dumps(got.get("segments") or [])))
            done.append({"id": str(job.id), "state": "done"})
        except Exception as e:  # noqa: BLE001
            if isinstance(e, (DeriveError, LookupError)):
                words = str(e)
            elif isinstance(e, subprocess.TimeoutExpired):
                words = "Reading this file took too long and was stopped. The original is unchanged."
            else:
                ref = uuid.uuid4().hex[:8]
                log.exception("phone derived text %s failed (reference %s)", job.id, ref)
                words = "This file could not be read. The original is unchanged. Reference: %s." % ref
            with engine.begin() as c:
                c.execute(text("UPDATE phone_derived_texts SET state = 'failed', error = :e, finished_at = now() "
                               "WHERE id = :i AND state = 'running' AND started_at = :t"), dict(guard, e=words))
            done.append({"id": str(job.id), "state": "failed"})
    return done


_worker = {"thread": None}


def _loop(engine, stop):
    while not stop.is_set():
        try:
            busy = run_pending(engine)
        except Exception:  # noqa: BLE001
            log.exception("phone derived text step failed")
            busy = []
        stop.wait(0 if busy else IDLE_SECONDS)


def start_worker(engine):
    """The sweep's after-pass hook: starts, once per process, the thread that reads requested media."""
    import threading
    t = _worker["thread"]
    if t is not None and t.is_alive():
        return
    from services.phone import sweep
    stop = sweep._STOP.get("event") or threading.Event()
    _worker["thread"] = threading.Thread(target=_loop, args=(engine, stop), name="phone-derive", daemon=True)
    _worker["thread"].start()


def install():
    from services.phone import sweep
    sweep.register_after_pass(start_worker)
