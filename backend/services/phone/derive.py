# run first in every child: no connection can leave the process, whatever a library tries
GUARD = r'''
import socket
def _refuse(*a, **k):
    raise OSError("outbound connections are refused while reading evidence")
socket.socket.connect = _refuse
socket.socket.connect_ex = _refuse
socket.create_connection = _refuse
'''
_CHILD = GUARD + r'''
import json, os, resource, sys
mb = int(os.environ.get("LOUPE_PHONE_DERIVE_MEMORY_MB", "6144"))
resource.setrlimit(resource.RLIMIT_AS, (mb * 1024 * 1024, mb * 1024 * 1024))
kind, path, model = sys.argv[1], sys.argv[2], sys.argv[3]
if kind == "transcript":
    import whisper
    m = whisper.load_model(model, device="cpu", download_root=os.path.dirname(model))
    r = m.transcribe(path, fp16=False, verbose=None)
    seg = [{"start": round(float(s["start"]), 2), "end": round(float(s["end"]), 2), "text": s["text"].strip()}
           for s in r.get("segments", [])]
    v = getattr(whisper, "__version__", "")
    print(json.dumps({"text": (r.get("text") or "").strip(), "segments": seg, "language": r.get("language"),
                      "package_version": v}))
'''


def _tesseract_version():
    try:
        out = subprocess.run(["tesseract", "--version"], capture_output=True, text=True, timeout=30)
    except (OSError, subprocess.TimeoutExpired):
        return None
    first = (out.stdout or out.stderr or "").strip().splitlines()
    return first[0].split()[-1] if first else None


def _ocr(path):
    version = _tesseract_version()
    pm = phone_media()
    langs = tesseract_languages()
    if version is None:
        raise DeriveError(NO_OCR)
    tessdata = pm.tessdata_dir(langs)
    if tessdata is None:
        raise DeriveError("The text reader has no language data for %s on this server. Nothing was sent anywhere."
                          % langs)
    ident = pm.tesseract_identity(version, tessdata, langs)
    import resource

    def cap():
        mb = int(os.environ.get("LOUPE_PHONE_DERIVE_MEMORY_MB", "6144"))
        resource.setrlimit(resource.RLIMIT_AS, (mb * 1024 * 1024, mb * 1024 * 1024))
    r = subprocess.run(["tesseract", str(path), "stdout", "--tessdata-dir", str(tessdata), "-l", langs],
                       capture_output=True, text=True,
                       timeout=TIMEOUT_SECONDS["ocr"], preexec_fn=cap, env={"PATH": os.environ.get("PATH", ""),
                                                                            "OMP_THREAD_LIMIT": "1"})
    if r.returncode != 0:
        raise DeriveError("The text reader could not read this image. The original is unchanged.")
    return dict(ident, text=r.stdout.strip(), segments=[], version=ident["model_version"],
                parameters={"languages": langs, "page_segmentation": "automatic (tesseract default 3)",
                            "engine": "tesseract default", "threads": 1})


def _transcribe(path):
    model = whisper_model_path()
    if not model.is_file():
        raise DeriveError(NO_MODEL)
    env = {k: v for k, v in os.environ.items() if k in ("PATH", "HOME", "LOUPE_PHONE_DERIVE_MEMORY_MB")}
    env.update({"HF_HUB_OFFLINE": "1", "OMP_NUM_THREADS": "2"})
    r = subprocess.run([sys.executable, "-I", "-c", _CHILD, "transcript", str(path), str(model)],
                       capture_output=True, text=True, timeout=TIMEOUT_SECONDS["transcript"], env=env)
    if r.returncode != 0:
        if "No module named 'whisper'" in (r.stderr or ""):
            raise DeriveError(NO_MODEL)
        raise DeriveError("This audio could not be transcribed. The original is unchanged.")
    got = json.loads(r.stdout.strip().splitlines()[-1])
    ident = phone_media().whisper_identity(model, got.get("package_version"))
    return dict(got, **ident, version=ident["model_version"],
                parameters={"device": "cpu", "fp16": False, "task": "transcribe", "language": "detected by the model",
                            "threads": int(env["OMP_NUM_THREADS"])})


def _duration(path):
    try:
        r = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "json", str(path)],
                           capture_output=True, text=True, timeout=60)
        d = (json.loads(r.stdout or "{}").get("format") or {}).get("duration")
        return float(d) if d not in (None, "N/A") else None
    except (OSError, ValueError, subprocess.TimeoutExpired):
        return None


def read_file(conn, case_id, file_uid, kind) -> dict:
    """Copy the file's bytes to a private temporary file (hashing them on the way), decide what the file is from
    its first bytes, read it in a child process, delete the copy."""
    import hashlib

    from services.phone import media
    pm = phone_media()
    pm.provider_for(kind)  # local only; a third-party provider would need a recorded case setting (05 17.4 point 3)
    name, _size, opener = media.content(conn, case_id, file_uid)
    with tempfile.TemporaryDirectory(prefix="loupe-derive-") as d:
        raw = Path(d) / "file"
        h = hashlib.sha256()
        with opener() as src, open(raw, "wb") as dst:
            while True:
                chunk = src.read(1 << 20)
                if not chunk:
                    break
                h.update(chunk)
                dst.write(chunk)
        found = pm.kind_of(raw, name)
        _check_kind(kind, found)
        wanted = ("image",) if kind == "ocr" else ("audio", "video")
        use_suffix = found.suffix and (found.container != "by-name" or found.kind in wanted)
        path = raw.rename(raw.with_suffix(found.suffix)) if use_suffix else raw
        got = _ocr(path) if kind == "ocr" else _transcribe(path)
        # what the bytes said; a guess from the name is not recorded as the file's kind
        got.update(input_sha256=h.hexdigest(),
                   sniffed_container="unrecognised" if found.container == "by-name" else found.container)
        if kind == "transcript":
            got["duration_seconds"] = _duration(path)
        return got


NOT_IMAGE = ("This file's contents are not a picture the text reader can open (its first bytes name %s). "
             "Nothing was read; the original is unchanged.")
NOT_AUDIO = ("This file's contents are not audio or video (its first bytes name %s). Nothing was transcribed; the "
             "original is unchanged.")
HEIF = ("This photo is stored as HEIC, which the text reader on this server cannot open. Nothing was read; the "
        "original is unchanged.")


def _check_kind(kind, found):
    """Refuse only when the bytes positively name another kind. Bytes that name nothing go to the reader, which
    decides (Tesseract opens JPEG 2000 and PNM; ffmpeg opens WMA, FLV, MTS and more than this sniffer names)."""
    if not found.recognised or found.container == "by-name":
        return  # only the bytes can refuse; a name is a guess
    what = "a %s file" % found.container.upper()
    if kind == "ocr":
        if found.kind != "image":
            raise DeriveError(NOT_IMAGE % what)
        if found.container == "heif":
            raise DeriveError(HEIF)
    elif found.kind not in ("audio", "video"):
        raise DeriveError(NOT_AUDIO % what)


def _claim(engine):
    while True:
        with engine.begin() as c:
            r = c.execute(text(
                "SELECT id, state, attempts FROM phone_derived_texts WHERE state = 'queued' OR (state = 'running' AND "
                "started_at < now() - make_interval(secs => CASE kind WHEN 'ocr' THEN :so ELSE :st END)) "
                "ORDER BY created_at FOR UPDATE SKIP LOCKED LIMIT 1"),
                {"so": STALE_SECONDS["ocr"], "st": STALE_SECONDS["transcript"]}).one_or_none()
            if r is None:
                return None
            if r.state == "running" and r.attempts >= MAX_ATTEMPTS:
                c.execute(text("UPDATE phone_derived_texts SET state = 'failed', error = :e, finished_at = now() "
                               "WHERE id = :i"), {"e": STOPPED, "i": r.id})
                continue
            return c.execute(text(
                "UPDATE phone_derived_texts SET state = 'running', started_at = clock_timestamp(), error = NULL, "
                "attempts = attempts + 1 WHERE id = :i RETURNING id, case_id, file_uid, kind, started_at"),
                {"i": r.id}).first()


def run_pending(engine, limit=1) -> list:
    done = []
    for _ in range(limit):
        job = _claim(engine)
        if job is None:
            break
        guard = {"i": job.id, "t": job.started_at}
        try:
            with engine.connect() as c:
                got = read_file(c, job.case_id, job.file_uid, job.kind)
            body = got.get("text") or ""
            with engine.begin() as c:
                c.execute(text(
                    "UPDATE phone_derived_texts SET state = 'done', text = :x, text_folded = :f, model = :m, "
                    "model_version = :v, segments = CAST(:s AS jsonb), model_id = :mi, weights_sha256 = :w, "
                    "input_sha256 = :ih, provider = :pr, sniffed_container = :sc, language = :lg, "
                    "duration_seconds = :du, parameters = CAST(:pa AS jsonb), finished_at = now() WHERE id = :i AND "
                    "state = 'running' AND started_at = :t"),
                    dict(guard, x=body, f=F.fold(body), m=got["model"], v=got["version"],
                         s=json.dumps(got.get("segments") or []), mi=got.get("model_id"),
                         w=got.get("weights_sha256"), ih=got.get("input_sha256"), pr=got.get("provider"),
                         sc=got.get("sniffed_container"), lg=got.get("language"), du=got.get("duration_seconds"),
                         pa=json.dumps(got.get("parameters") or {})))
            done.append({"id": str(job.id), "state": "done"})
        except Exception as e:  # noqa: BLE001
            from services.phone.archive_member import MemberDamaged
            if isinstance(e, (DeriveError, LookupError, MemberDamaged)):
                words = str(e)
            elif isinstance(e, subprocess.TimeoutExpired):
                words = "Reading this file took too long and was stopped. The original is unchanged."
            else:
                ref = uuid.uuid4().hex[:8]
                log.exception("phone derived text %s failed (reference %s)", job.id, ref)
                words = "This file could not be read. The original is unchanged. Reference: %s." % ref
            with engine.begin() as c:
                c.execute(text("UPDATE phone_derived_texts SET state = 'failed', error = :e, finished_at = now() "
                               "WHERE id = :i AND state = 'running' AND started_at = :t"), dict(guard, e=words))
            done.append({"id": str(job.id), "state": "failed"})
    return done


_worker = {"thread": None}


def _loop(engine, stop):
    while not stop.is_set():
        try:
            busy = run_pending(engine)
        except Exception:  # noqa: BLE001
            log.exception("phone derived text step failed")
            busy = []
        stop.wait(0 if busy else IDLE_SECONDS)


def start_worker(engine):
    """The sweep's after-pass hook: starts, once per process, the thread that reads requested media."""
    import threading
    t = _worker["thread"]
    if t is not None and t.is_alive():
        return
    from services.phone import sweep
    stop = sweep._STOP.get("event") or threading.Event()
    _worker["thread"] = threading.Thread(target=_loop, args=(engine, stop), name="phone-derive", daemon=True)
    _worker["thread"].start()


def install():
    from services.phone import sweep
    sweep.register_after_pass(start_worker)
