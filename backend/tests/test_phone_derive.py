FONT = Path(__file__).resolve().parents[1] / "assets" / "fonts" / "NotoSans-Regular.ttf"
OGG = b"OggS\x00\x02" + b"\x00" * 20 + b"OpusHead" + b"\x00" * 64  # an Ogg Opus header (synthetic)


def _place(world, tmp_path, monkeypatch, uid, relpath, data, category):
    engine, case, _, ext = world
    monkeypatch.setattr("config.EVIDENCE_DATA_ROOT", str(tmp_path))
    target = tmp_path / str(case) / "up" / "root" / relpath
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_bytes(data)
    with engine.begin() as c:
        c.execute(text("UPDATE phone_files SET disk_relpath = :r, disk_size = :n, tags = :t WHERE file_uid = :f"),
                  {"r": relpath, "n": len(data), "t": category, "f": uid})
        cid = c.execute(text("SELECT first_container_id FROM phone_extractions WHERE id = :e"), {"e": ext}).scalar()
        c.execute(text("UPDATE phone_extraction_containers SET container_kind = 'folder', stored_path = 'up' WHERE "
                       "id = :i"), {"i": cid})
        c.execute(text("DELETE FROM phone_extraction_container_links WHERE extraction_id = :e"), {"e": ext})
        c.execute(text("INSERT INTO phone_extraction_container_links (extraction_id, container_id, root_path) VALUES "
                       "(:e, :i, 'root')"), {"e": ext, "i": cid})
    return target


def _image():
    import io

    from PIL import Image, ImageDraw, ImageFont
    img = Image.new("RGB", (900, 160), "white")
    ImageDraw.Draw(img).text((30, 40), "SYNTHETIC HARBOUR NOTICE", fill="black",
                             font=ImageFont.truetype(str(FONT), 56))
    buf = io.BytesIO()
    img.save(buf, format="JPEG", quality=95)
    return buf.getvalue()


@pytest.mark.skipif(shutil.which("tesseract") is None, reason="tesseract is not installed")
def test_m3_a_photos_text_is_read_labelled_searchable_and_the_original_is_unchanged(world, tmp_path, monkeypatch):
    from services.phone import derive
    from services.search import search as S
    engine, case, _, ext = world
    target = _place(world, tmp_path, monkeypatch, LINKED, "chats/synthetic-a.jpg", _image(), "Image")
    before = hashlib.sha256(target.read_bytes()).hexdigest()
    with engine.begin() as c:
        first = derive.request(c, case, LINKED, "ocr")
        again = derive.request(c, case, LINKED, "ocr")
    assert first["state"] == "queued" and again["id"] == first["id"]
    assert derive.run_pending(engine) == [{"id": first["id"], "state": "done"}]
    with engine.connect() as c:
        [got] = derive.list_for(c, case, LINKED)
        hits = {g["group"]: g for g in S.search(c, case, "harbour")["groups"]}
    assert got["state"] == "done" and got["machine_generated"] and got["model"] == "Tesseract"
    assert got["model_version"] and "HARBOUR" in got["text"].upper()
    assert got["label"].startswith("Machine-generated by Tesseract %s on " % got["model_version"])
    assert got["label"].endswith("The original is above.")
    g = hits["machine_text"]
    assert g["total"] == 1 and g["items"][0]["machine_generated"] and g["items"][0]["file_uid"] == LINKED
    assert g["items"][0]["open"] == {"screen": "media", "params": {"file_uid": LINKED, "extraction_id": str(ext)}}
    assert hits["messages"]["total"] == 0  # the derived text is its own kind, never a message
    assert hashlib.sha256(target.read_bytes()).hexdigest() == before
    with engine.connect() as c:
        assert S.search(c, world[2], "harbour", groups=("machine_text",))["groups"][0]["total"] == 0  # another case sees nothing


