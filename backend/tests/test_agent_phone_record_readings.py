"""The agent's phone_record shows the text read from each photo the record carries (07 4.6). Probe 22 Nov: four
demo photos had a Tesseract reading stored, but the record tool listed only their file names, so the agent said they
"were not read as images". Synthetic data; needs the PostgreSQL template."""
from __future__ import annotations

from sqlalchemy import text

from tests.phone_pg import needs_template
from tests.test_phone_machine_text import _done
from tests.test_phone_media import LINKED, world  # noqa: F401 (fixture)
from tests.test_phone_mappings import hooks  # noqa: F401 (fixture)

pytestmark = needs_template


def _carrier(engine, case):
    with engine.connect() as c:
        return c.execute(text("SELECT record_uid FROM pv_attachment_link WHERE case_id = :c AND file_uid = :f"),
                         {"c": str(case), "f": LINKED}).scalar()


def test_a_read_photo_shows_its_text_as_a_machine_reading_and_an_unread_one_says_so(world):  # noqa: F811
    from services.agent import phone_tools as PT
    engine, case, _other, ext = world
    rec = _carrier(engine, case)
    assert rec is not None
    with engine.connect() as c:
        before = PT.record(c, case, rec)["items"][0]["file_readings"]
    linked = [f for f in before if f["readings"] or f["none"]]
    assert linked and all(f["readings"] == [] and f["none"] == PT.NO_READING for f in before)
    _done(engine, case, ext, words="SERIAL TVN20-118204")
    with engine.connect() as c:
        item = PT.record(c, case, rec)["items"][0]
    got = [r for f in item["file_readings"] for r in f["readings"]]
    assert len(got) == 1
    assert got[0]["text"] == "SERIAL TVN20-118204"
    assert got[0]["kind"] == "Text read from the image"
    assert got[0]["origin"].startswith("Machine-generated by Tesseract 5.3.4") and "not yet confirmed" in got[0]["origin"]
