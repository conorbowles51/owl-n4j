"""07 5 Media (M-7): an export of messages whose attachment carries a machine transcript lists the transcript for
the prompt "This transcript is machine-generated. Listen and confirm, or keep it marked", and prints it under the
attachment with its mark: not yet confirmed, confirmed, or corrected (where the corrected text is printed).

Invented data only. Needs the PostgreSQL phone template and WeasyPrint.
"""
from __future__ import annotations

import uuid
from datetime import datetime, timezone
from types import SimpleNamespace

import pytest
from sqlalchemy import text

from tests.test_phone_exports import _export, world  # noqa: F401 (fixture)

pytest.importorskip("weasyprint")
FILE = str(uuid.UUID("00000000-0000-4000-8000-00000000a0d1"))
WORDS = "SYNTHETIC SPOKEN HARBOUR WORDS"


def _voice_note(w):
    ident = uuid.uuid4()
    with w["engine"].begin() as c:
        c.execute(text("INSERT INTO phone_files (extraction_id, document_index, ordinal, file_uid, local_path, outcome, "
                       "body) VALUES (:e, 0, 9000, :f, 'voice/synthetic-note.ogg', 'match', CAST('[]' AS jsonb))"),
                  {"e": w["ext"], "f": FILE})
        c.execute(text(  # attached to the first message (record ordinal 0)
            "INSERT INTO phone_file_references (extraction_id, document_index, record_ordinal, body_path, mechanism, "
            "reference_text, file_document_index, file_ordinal, resolution, ambiguous) VALUES (:e, 0, 0, 'f', "
            "'extracted_path_value', 'voice/synthetic-note.ogg', 0, 9000, 'container_entry', false)"),
            {"e": w["ext"]})
        c.execute(text(
            "INSERT INTO phone_derived_texts (id, case_id, extraction_id, file_uid, kind, state, text, text_folded, "
            "model, model_version, finished_at) VALUES (:i, :c, :e, :f, 'transcript', 'done', :t, lower(:t), "
            "'Whisper', 'base 20250625', :at)"),
            {"i": ident, "c": w["case"], "e": w["ext"], "f": FILE, "t": WORDS,
             "at": datetime(2026, 11, 3, tzinfo=timezone.utc)})
    return ident


def _describe(w):
    from services.phone.exports import jobs
    with w["engine"].connect() as c:
        return jobs.describe_machine_text(c, w["case"], {"zone": {"mode": "case"}})


def test_m7_an_unconfirmed_transcript_is_listed_for_the_prompt_and_printed_with_its_mark(world):
    assert _describe(world)["total"] == 0  # no machine text: nothing to ask
    ident = _voice_note(world)
    d = _describe(world)
    assert (d["total"], d["unconfirmed"]) == (1, 1)
    [item] = d["items"]
    assert item["id"] == str(ident) and item["file_uid"] == FILE and item["kind"] == "transcript"
    assert item["filename"] == "synthetic-note.ogg" and item["words"].endswith("not yet confirmed")
    state, _, txt = _export(world)
    words = " ".join(txt.split())
    assert "Transcript: %s" % WORDS in words
    assert "Machine-generated by Whisper base 20250625 on " in words and "not yet confirmed" in words
    assert ("1 machine-generated text (transcripts or text read from images) is printed under its attachment; 1 is not "
            "yet confirmed by a person, and each says so.") in words
    assert (state["counts"]["machine_texts"], state["counts"]["machine_texts_unconfirmed"]) == (1, 1)


def test_m7_a_corrected_transcript_prints_the_correction_and_its_mark_and_leaves_the_prompt(world):
    from sqlalchemy.orm import Session

    from services.phone import machine_text
    ident = _voice_note(world)
    with Session(bind=world["engine"]) as db:
        machine_text.correct(db, case_id=world["case"], derived_id=ident, text="SYNTHETIC SPOKEN HARBOUR MOTION",
                             reason="heard it", user=SimpleNamespace(id=None, name="Synthetic Reviewer",
                                                                     email="reviewer@synthetic.test"))
        db.commit()
    d = _describe(world)
    assert (d["total"], d["unconfirmed"], d["items"]) == (1, 0, [])
    _, _, txt = _export(world)
    words = " ".join(txt.split())
    assert "Transcript: SYNTHETIC SPOKEN HARBOUR MOTION" in words and WORDS not in words
    assert "Corrected by Synthetic Reviewer on " in words and ": heard it" in words


def test_m7_another_cases_transcript_is_never_listed(world):
    _voice_note(world)
    from services.phone.exports import jobs
    with world["engine"].connect() as c:
        assert jobs.describe_machine_text(c, world["other"], {"zone": {"mode": "case"}})["total"] == 0


def test_m7_the_pdf_prints_the_persons_correction_even_after_a_later_machine_reading(world):
    from sqlalchemy.orm import Session

    from services.phone import machine_text
    ident = _voice_note(world)
    with Session(bind=world["engine"]) as db:
        machine_text.correct(db, case_id=world["case"], derived_id=ident, text="SYNTHETIC SPOKEN HARBOUR MOTION",
                             reason="heard it", user=SimpleNamespace(id=None, name="Synthetic Reviewer",
                                                                     email="reviewer@synthetic.test"))
        db.commit()
    with world["engine"].begin() as c:
        c.execute(text(
            "INSERT INTO phone_derived_texts (id, case_id, extraction_id, file_uid, kind, state, text, text_folded, "
            "model, model_version, finished_at) VALUES (gen_random_uuid(), :c, :e, :f, 'transcript', 'done', "
            "'SYNTHETIC LATER WORDS', 'synthetic later words', 'Whisper', 'base 20250625', now())"),
            {"c": world["case"], "e": world["ext"], "f": FILE})
    assert _describe(world)["unconfirmed"] == 0
    _, _, txt = _export(world)
    words = " ".join(txt.split())
    assert "Transcript: SYNTHETIC SPOKEN HARBOUR MOTION" in words and "SYNTHETIC LATER WORDS" not in words
