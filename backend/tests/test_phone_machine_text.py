def test_co18_a_transcript_accepted_into_a_dossier_assessment_is_ai_assisted_and_names_its_reader(world):
    from sqlalchemy.orm import Session

    from postgres.models.user import User
    from services.phone import derive, machine_text, resolvers
    resolvers.register()  # as the backend does at start
    engine, case, other, ext = world
    ident = _done(engine, case, ext, words="SYNTHETIC SPOKEN WORDS", kind="transcript")
    with engine.begin() as c:
        owner = c.execute(text("SELECT owner_user_id FROM cases WHERE id = :c"), {"c": case}).scalar()
        mk = ("INSERT INTO case_profiles (id, case_id, profile_type, display_name, created_at, updated_at) VALUES "
              "(gen_random_uuid(), :c, 'person', 'Synthetic Person', now(), now()) RETURNING id")
        dossier = c.execute(text(mk), {"c": case}).scalar()
        elsewhere = c.execute(text(mk), {"c": other}).scalar()
    with Session(bind=engine) as db:
        user = db.get(User, owner)
        with pytest.raises(LookupError):
            machine_text.accept_into_assessment(db, case_id=case, derived_id=ident, dossier_id=elsewhere,
                                                category="Statement", user=user)
        out = machine_text.accept_into_assessment(db, case_id=case, derived_id=ident, dossier_id=dossier,
                                                  category="Statement", user=user)
        db.commit()
    assert out["provenance_type"] == "ai_assisted" and out["derived_text_id"] == str(ident)
    assert out["content"] == "SYNTHETIC SPOKEN WORDS"
    assert out["read_by"] == "Read by Tesseract 5.3.4, accepted by synthetic"
    [link] = out["supporting_links"]
    assert link["target_type"] == "phone_file" and link["target_id"] == LINKED
    assert link["source_anchor"]["derived_text_id"] == str(ident)
    with engine.connect() as c:
        [got] = derive.list_for(c, case, LINKED)
    assert got["origin"]["state"] == "machine"  # accepting is not confirming: the text keeps its mark


def test_m6_a_later_machine_reading_never_displaces_a_persons_correction(world):
    """Review finding on 8f4a6141: a re-reading finished after a correction took over search; the person's reading
    must stay the one used, and the screen says which reading is used."""
    from services.phone import derive, machine_text
    from services.search import search as S
    engine, case, _, ext = world
    first = _done(engine, case, ext)
    with _session(engine) as db:
        machine_text.correct(db, case_id=case, derived_id=first, text="SYNTHETIC HARBOUR MOTION", reason="read it",
                             user=USER)
        db.commit()
    later = uuid.uuid4()
    with engine.begin() as c:  # a re-reading of the same file finishes later
        c.execute(text(
            "INSERT INTO phone_derived_texts (id, case_id, extraction_id, file_uid, kind, state, text, text_folded, "
            "model, model_version, finished_at) VALUES (:i, :c, :e, :f, 'ocr', 'done', 'SYNTHETIC HARBOUR NOTION', "
            "'synthetic harbour notion', 'Tesseract', '5.3.4', now())"), {"i": later, "c": case, "e": ext, "f": LINKED})
    with engine.connect() as c:
        hits = {g["group"]: g for g in S.search(c, case, "motion")["groups"]}["machine_text"]
        stale = {g["group"]: g for g in S.search(c, case, "notion")["groups"]}["machine_text"]
        rows = {r["id"]: r for r in derive.list_for(c, case, LINKED)}
    assert hits["total"] == 1 and stale["total"] == 0
    assert rows[str(first)]["in_use"] and not rows[str(later)]["in_use"]


