class AbaRoutingTests(unittest.TestCase):
    """Nine digits, weights 3-7-1 repeating, sum a multiple of ten."""

    #: Live Federal Reserve routing numbers.  Not generated by this module.
    REAL = ("021000021", "011000015", "121000248", "071000013", "026009593")

    def test_real_routing_numbers_pass(self) -> None:
        for value in self.REAL:
            with self.subTest(value):
                result = verify(IdentifierKind.aba_routing, value)
                self.assertIs(result.outcome, CheckDigitOutcome.passed)
                self.assertEqual(
                    result.checks_performed,
                    (CHECK_STRUCTURE, CHECK_ABA_WEIGHTED_MOD10),
                )

    def test_the_failure_names_the_digit_it_expected(self) -> None:
        """So the reader can see the size of the discrepancy.

        A check digit off by one is a different kind of event from one that
        is off by five, and the second is much less likely to be a single
        misread character.  Stating both numbers lets that be judged without
        re-running anything.
        """
        result = verify(IdentifierKind.aba_routing, "021000022")
        self.assertIs(result.outcome, CheckDigitOutcome.failed)
        self.assertIn("check digit of 1", result.detail)
        self.assertIn("9th digit is 2", result.detail)

    def test_every_prefix_implies_exactly_one_valid_ninth_digit(self) -> None:
        """The property that makes the check worth anything.

        If two ninth digits verified for one prefix the check would catch half
        of what it claims to.  Swept over a thousand random prefixes rather
        than argued from the weights.
        """
        rng = random.Random(3)
        for _ in range(1000):
            prefix = f"{rng.randrange(10 ** 8):08d}"
            valid = [
                d
                for d in "0123456789"
                if verify(IdentifierKind.aba_routing, prefix + d).outcome
                is CheckDigitOutcome.passed
            ]
            self.assertEqual(len(valid), 1, prefix)
            self.assertEqual(int(valid[0]), aba_check_digit(prefix))

    def test_a_prefix_that_is_not_eight_digits_computes_nothing(self) -> None:
        for prefix in ("0210000", "021000021", "0210000A", "", "0210000 "):
            with self.subTest(prefix):
                self.assertIsNone(aba_check_digit(prefix))


class PaymentCardTests(unittest.TestCase):
    """ISO/IEC 7812-1 length, then Luhn."""

    #: Published network test numbers, plus the Wikipedia Luhn example.
    PUBLISHED = (
        "4111111111111111",
        "5500005555555559",
        "378282246310005",
        "6011111111111117",
        "3530111333300000",
        "79927398713",
    )

    def test_published_card_numbers_pass(self) -> None:
        for value in self.PUBLISHED:
            with self.subTest(value):
                if len(value) < cd.CARD_MIN_DIGITS:
                    continue
                result = verify(IdentifierKind.payment_card, value)
                self.assertIs(result.outcome, CheckDigitOutcome.passed)
                self.assertEqual(
                    result.checks_performed, (CHECK_STRUCTURE, CHECK_LUHN_MOD10)
                )

    def test_the_eleven_digit_luhn_example_is_too_short_to_be_a_card(self) -> None:
        """``79927398713`` checks out under Luhn and is not a card number.

        The distinction the two-stage check keeps: the arithmetic is fine and
        the value is still not the thing the caller said it was.  Reported as
        malformed, because that is a statement about shape.
        """
        self.assertEqual(luhn_residue("79927398713"), 0)
        result = verify(IdentifierKind.payment_card, "79927398713")
        self.assertIs(result.outcome, CheckDigitOutcome.malformed)
        self.assertIn("12 to 19", result.detail)

    def test_the_failure_states_the_residue(self) -> None:
        result = verify(IdentifierKind.payment_card, "4111111111111112")
        self.assertIs(result.outcome, CheckDigitOutcome.failed)
        self.assertIn("Luhn sum is 1", result.detail)

    def test_grouping_spaces_and_hyphens_are_not_an_error(self) -> None:
        """How a card number is written on a statement is not a finding."""
        for value in (
            "4111 1111 1111 1111",
            "4111-1111-1111-1111",
            "4111 1111-1111 1111",
        ):
            with self.subTest(value):
                result = verify(IdentifierKind.payment_card, value)
                self.assertIs(result.outcome, CheckDigitOutcome.passed)
                self.assertEqual(result.normalised, "4111111111111111")


