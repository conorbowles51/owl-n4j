class CoverageTests(unittest.TestCase):
    """That the dispatch table and the vocabulary cannot drift apart."""

    def test_every_identifier_kind_has_a_verifier(self) -> None:
        """Adding a member without a verifier should be caught here, not live.

        The guard inside :func:`verify` raises rather than falling through, but
        it raises at the call site — which in this system means during an
        ingestion run, over somebody's evidence.  This test moves the failure
        to where it is cheap.
        """
        self.assertEqual(set(cd._VERIFIERS), set(IdentifierKind))

    def test_a_kind_with_no_verifier_raises_rather_than_returning_a_verdict(
        self,
    ) -> None:
        """The unreachable branch, reached deliberately, because it matters.

        The test above keeps the dispatch table complete, so in a healthy tree
        this branch never runs.  That is exactly why it needs a test of its
        own: it is the code that decides what happens on the day the table
        *is* incomplete, and an untested branch there could be quietly changed
        to return a result instead of raising.  A returned result would be
        filed against the row as though a check had been performed on it.

        The table is restored in ``finally`` so a failure here cannot leak into
        the tests that follow.
        """
        original = dict(cd._VERIFIERS)
        try:
            del cd._VERIFIERS[IdentifierKind.iban]
            with self.assertRaises(CheckDigitError):
                verify(IdentifierKind.iban, "GB82WEST12345698765432")
        finally:
            cd._VERIFIERS.clear()
            cd._VERIFIERS.update(original)
        self.assertEqual(set(cd._VERIFIERS), set(IdentifierKind))

    def test_every_kind_returns_a_result_naming_itself(self) -> None:
        """No verifier may return a verdict labelled as a neighbouring kind."""
        for kind in IdentifierKind:
            with self.subTest(kind):
                result = verify(kind, "021000021")
                self.assertIsInstance(result, CheckDigitResult)
                self.assertIs(result.kind, kind)
                self.assertIsInstance(result.outcome, CheckDigitOutcome)
                self.assertIsInstance(result.checks_performed, tuple)

    def test_every_check_name_is_reachable(self) -> None:
        """A constant no result ever carries is a name for nothing."""
        seen: set[str] = set()
        for kind, value in [
            (IdentifierKind.iban, "GB82WEST12345698765432"),
            (IdentifierKind.lei, "5493001KJTIIGC8Y1R12"),
            (IdentifierKind.aba_routing, "021000021"),
            (IdentifierKind.payment_card, "4111111111111111"),
            (IdentifierKind.bic, "DEUTDEFF"),
            (IdentifierKind.us_ssn, "123456789"),
            (IdentifierKind.us_ein, "123456789"),
        ]:
            seen.update(verify(kind, value).checks_performed)
        self.assertEqual(
            seen,
            {
                CHECK_STRUCTURE,
                CHECK_ISO7064_MOD97_10,
                CHECK_ABA_WEIGHTED_MOD10,
                CHECK_LUHN_MOD10,
                CHECK_IBAN_COUNTRY_LENGTH,
                CHECK_SSN_ISSUED_RANGES,
            },
        )

    def test_a_pass_never_carries_a_detail(self) -> None:
        """Detail is the reason for a verdict, and a pass has no reason."""
        for kind, value in [
            (IdentifierKind.iban, "GB82WEST12345698765432"),
            (IdentifierKind.lei, "5493001KJTIIGC8Y1R12"),
            (IdentifierKind.aba_routing, "021000021"),
            (IdentifierKind.payment_card, "4111111111111111"),
        ]:
            with self.subTest(kind):
                result = verify(kind, value)
                self.assertIs(result.outcome, CheckDigitOutcome.passed)
                self.assertEqual(result.detail, "")

    def test_every_non_pass_carries_a_detail(self) -> None:
        """And a verdict that is not a pass always explains itself."""
        for kind, value in [
            (IdentifierKind.iban, "GB82WEST12345698765433"),
            (IdentifierKind.iban, "nonsense"),
            (IdentifierKind.lei, "5493001KJTIIGC8Y1R13"),
            (IdentifierKind.aba_routing, "021000022"),
            (IdentifierKind.payment_card, "4111111111111112"),
            (IdentifierKind.bic, "DEUTDEFF"),
            (IdentifierKind.us_ssn, "666456789"),
            (IdentifierKind.us_ein, "123456789"),
        ]:
            with self.subTest((kind, value)):
                result = verify(kind, value)
                self.assertIsNot(result.outcome, CheckDigitOutcome.passed)
                self.assertTrue(result.detail)


