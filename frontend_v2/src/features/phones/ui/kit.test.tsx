describe("result count (07 4.8)", () => {
  it("states shown of total with separators, never N / M", () => {
    expect(countSentence({ shown: 1204, total: 1260, noun: "messages" })).toBe("Showing 1,204 of 1,260 messages")
    expect(countSentence({ shown: 186787, total: 186787, noun: "messages" })).toBe("186,787 messages")
    expect(countSentence({ shown: 1, total: 1, noun: "messages" })).toBe("1 message")
    expect(countSentence({ shown: 10, total: 20, noun: "calls", soFar: true })).toBe("Showing 10 of 20 calls (so far)")
  })
  it("gives the reason and the unconfirmed count", () => {
    render(<ResultCount shown={1204} total={1260} noun="positioned records" reason="56 cannot be placed" unconfirmed={41233} />)
    const p = screen.getByTestId("result-count")
    expect(p.textContent).toContain("Showing 1,204 of 1,260 positioned records")
    expect(p.textContent).toContain("56 cannot be placed.")
    expect(p.textContent).toContain("41,233 not yet confirmed")
    expect(p.textContent).not.toMatch(/\d+ ?\/ ?\d+/)
  })
})

describe("origin mark (07 4.6)", () => {
  it("uses the fixed words for every state", () => {
    expect(originWords({ state: "report" })).toBeNull()
    expect(originWords({ state: "unconfirmed" })).toBe("Mapped by the system, not yet confirmed")
    expect(originWords({ state: "machine", model: "Whisper", version: "v3", on: "4 Mar 2024" })).toBe("Machine-generated by Whisper v3 on 4 Mar 2024, not yet confirmed")
    expect(originWords({ state: "confirmed", by: "Sam Reviewer", on: "4 Mar 2024" })).toBe("Confirmed by Sam Reviewer on 4 Mar 2024")
    expect(originWords({ state: "accepted", model: "the agent", by: "Sam Reviewer", on: "4 Mar 2024" })).toBe("Read by the agent, accepted by Sam Reviewer on 4 Mar 2024")
    expect(originWords({ state: "corrected", by: "Sam Reviewer", on: "4 Mar 2024", reason: "sender was the other party", original: "A" })).toBe("Corrected by Sam Reviewer on 4 Mar 2024: sender was the other party")
  })
  it("a correction keeps the original visible", () => {
    render(<OriginMark origin={{ state: "corrected", by: "Sam", on: "4 Mar", reason: "typo", original: "Avery Q." }} />)
    expect(screen.getByText("Avery Q.")).toBeInTheDocument()
    expect(screen.getByRole("link", { name: /Learn more: Corrected/ })).toHaveAttribute("href", "/guide/phones#corrected")
  })
  it("badges follow priority, show two and name the rest in +N", () => {
    expect(orderBadges(["duplicate", "deleted", "corrected", "unconfirmed"])).toEqual(["corrected", "unconfirmed", "deleted", "duplicate"])
    render(<BadgeRow badges={["duplicate", "deleted", "corrected", "unconfirmed"]} />)
    expect(screen.getByText("Corrected")).toBeInTheDocument()
    expect(screen.getByText("Not yet confirmed")).toBeInTheDocument()
    expect(screen.queryByText("Deleted")).toBeNull()
    expect(screen.getByLabelText("2 more: Deleted, Found more than once")).toHaveTextContent("+2")
  })
  it("every glossary sentence is plain: no em dash, no field names", () => {
    for (const e of GLOSSARY) {
      expect(e.meaning).not.toContain("—")
      expect(e.meaning).not.toMatch(/[a-z]+_[a-z]+|InstantMessage|deleted_state/)
    }
  })
})

