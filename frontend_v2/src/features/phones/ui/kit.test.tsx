describe("keymap registry (07 4.9)", () => {
  it("refuses a key with no fixed meaning", () => {
    expect(() => register("Test", [{ key: "q", label: "Quit", run: () => {} }])).toThrow(/no meaning/)
  })
  it("names keys the same way across layouts", () => {
    expect(keyName(key("j"))).toBe("j")
    expect(keyName(key("J", { shiftKey: true }))).toBe("Shift+J")
    expect(keyName(key("∆", { altKey: true, code: "KeyJ" }))).toBe("Alt+J")
    expect(keyName(key("f", { ctrlKey: true }))).toBe("Mod+F")
    expect(keyName(key("?", { shiftKey: true }))).toBe("?")
  })
  it("dispatches, runs c then d as a sequence, and ignores keys while typing", () => {
    const moved = vi.fn()
    const dossier = vi.fn()
    register("Conversations", [
      { key: "j", label: "Next message", run: moved },
      { key: "c d", label: "Add to a dossier", run: dossier },
    ])
    expect(dispatchKey(key("j"))).toBe(true)
    expect(moved).toHaveBeenCalledTimes(1)
    dispatchKey(key("c"), 1000)
    dispatchKey(key("d"), 1200)
    expect(dossier).toHaveBeenCalledTimes(1)
    const input = document.createElement("input")
    document.body.appendChild(input)
    const typed = new KeyboardEvent("keydown", { key: "j", cancelable: true })
    Object.defineProperty(typed, "target", { value: input })
    expect(dispatchKey(typed)).toBe(false)
    expect(moved).toHaveBeenCalledTimes(1)
    input.remove()
  })
  it("the ? overlay lists what is registered now, with the screen's own labels", async () => {
    register("Needs a decision", [{ key: "y", label: "Looks right", run: () => {} }, { key: "x", label: "Not right", run: () => {} }])
    render(<KeymapOverlay />)
    act(() => {
      dispatchKey(key("?", { shiftKey: true }))
    })
    expect(await screen.findByRole("dialog", { name: "Keys on this screen" })).toBeInTheDocument()
    expect(screen.getByText("Looks right")).toBeInTheDocument()
    expect(screen.getByText("Not right")).toBeInTheDocument()
  })
})

describe("phone selection store (07 4.2 item 7)", () => {
  it("never cuts the selection, and states the whole result", () => {
    const s = usePhoneSelection.getState()
    s.setCase("case-1")
    const order = Array.from({ length: 412 }, (_, i) => `r${i}`)
    s.toggle("r0")
    usePhoneSelection.getState().extendTo("r411", order)
    expect(usePhoneSelection.getState().ids).toHaveLength(412)
    expect(selectionSentence(usePhoneSelection.getState(), "messages")).toBe("412 messages selected")
    usePhoneSelection.getState().selectWhole({ total: 186787, noun: "messages", scope: "all threads", scopeKey: "s" })
    expect(selectionSentence(usePhoneSelection.getState())).toBe("All 186,787 messages selected")
    usePhoneSelection.getState().setCase("case-2")
    expect(usePhoneSelection.getState().whole).toBeNull()
  })
})

describe("copy helper on plain http (07 4.10)", () => {
  it("writes plain text and HTML through the copy event inside the gesture", () => {
    const data: Record<string, string> = {}
    const exec = vi.fn(() => {
      const event = new Event("copy", { cancelable: true }) as ClipboardEvent
      Object.defineProperty(event, "clipboardData", { value: { setData: (t: string, v: string) => (data[t] = v) } })
      document.dispatchEvent(event)
      return true
    })
    Object.defineProperty(document, "execCommand", { value: exec, configurable: true })
    expect(copyInGesture({ text: "A (+12015550100) → B", html: "<p>A</p>" })).toBe(true)
    expect(data["text/plain"]).toBe("A (+12015550100) → B")
    expect(data["text/html"]).toBe("<p>A</p>")
  })
  it("over 5,000 rows takes two steps, and a refusal shows the text selected", () => {
    const exec = vi.fn(() => false)
    Object.defineProperty(document, "execCommand", { value: exec, configurable: true })
    const build = vi.fn(() => ({ text: "many rows" }))
    render(<CopyButton build={build} rows={12345} noun="messages" />)
    fireEvent.click(screen.getByRole("button", { name: "Copy" }))
    expect(screen.getByRole("status")).toHaveTextContent("12,345 messages are ready to copy. Copy now.")
    expect(exec).not.toHaveBeenCalled()
    fireEvent.click(screen.getByRole("button", { name: "Copy now" }))
    expect(exec).toHaveBeenCalledTimes(1)
    expect(screen.getByRole("alert")).toHaveTextContent("press Ctrl+C")
    expect(screen.getByText("many rows")).toBeInTheDocument()
  })
})
