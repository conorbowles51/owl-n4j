import { Bot, CircleAlert, CircleCheck, CopyIcon, History, PencilLine, Smartphone, Trash2 } from "lucide-react"
import type { ComponentType } from "react"
import { cn } from "@/lib/cn"
import { GLOSSARY_BY_ID, guideHref } from "../glossary"

/**
 * Where each value came from: one origin mark (07 4.6). Screen, copy and PDF print the same words, so the words
 * come from originWords(), which the copy helper and export use too.
 */
export type Origin =
  | { state: "report" }
  | { state: "unconfirmed"; rule?: string }
  | { state: "machine"; model: string; version?: string; on: string }
  | { state: "confirmed"; by: string; on: string }
  | { state: "accepted"; model: string; by: string; on: string }
  | { state: "corrected"; by: string; on: string; reason: string; original: string }

export function originWords(origin: Origin): string | null {
  switch (origin.state) {
    case "report":
      return null
    case "unconfirmed":
      return "Mapped by the system, not yet confirmed"
    case "machine":
      return `Machine-generated by ${origin.model}${origin.version ? ` ${origin.version}` : ""} on ${origin.on}, not yet confirmed`
    case "confirmed":
      return `Confirmed by ${origin.by} on ${origin.on}`
    case "accepted":
      return `Read by ${origin.model}, accepted by ${origin.by} on ${origin.on}`
    case "corrected":
      return `Corrected by ${origin.by} on ${origin.on}: ${origin.reason}`
  }
}

const GLOSSARY_FOR: Record<Origin["state"], string> = {
  report: "record",
  unconfirmed: "unconfirmed",
  machine: "machine",
  confirmed: "confirmed",
  accepted: "accepted",
  corrected: "corrected",
}

const TONE: Record<Origin["state"], string> = {
  report: "",
  unconfirmed: "text-status-review bg-status-review-soft",
  machine: "text-status-model bg-status-model-soft",
  confirmed: "text-foreground",
  accepted: "text-status-model bg-status-model-soft",
  corrected: "text-status-review bg-status-review-soft",
}

const ICON: Partial<Record<Origin["state"], ComponentType<{ className?: string; "aria-hidden"?: boolean }>>> = {
  unconfirmed: CircleAlert,
  machine: Bot,
  accepted: Bot,
  corrected: PencilLine,
  confirmed: CircleCheck,
}

export function OriginMark({ origin, onRule, className }: { origin: Origin; onRule?: () => void; className?: string }) {
  const words = originWords(origin)
  if (!words) return null
  const Icon = ICON[origin.state]
  const entry = GLOSSARY_BY_ID[GLOSSARY_FOR[origin.state]]
  return (
    <span className={cn("inline-flex flex-wrap items-center gap-1.5 rounded-sm px-1.5 py-0.5 text-xs", TONE[origin.state], className)} data-origin={origin.state}>
      {Icon && <Icon className="size-3.5 shrink-0" aria-hidden />}
      {origin.state === "unconfirmed" && origin.rule && onRule ? (
        <button type="button" className="underline underline-offset-2" onClick={onRule} title={origin.rule}>
          {words}
        </button>
      ) : (
        <span>{words}</span>
      )}
      {origin.state === "corrected" && (
        <span className="text-foreground">
          (original: <span className="line-through decoration-1">{origin.original}</span>)
        </span>
      )}
      <a href={guideHref(entry)} className="underline underline-offset-2" aria-label={`Learn more: ${entry.term}`}>
        Learn more
      </a>
    </span>
  )
}

/** Badges on a row (07 4.6): priority order, two shown, "+N" names the rest. */
export type RowBadge = "corrected" | "unconfirmed" | "deleted" | "trash" | "carved" | "synced" | "duplicate" | "other-phone"

export const BADGE_PRIORITY: RowBadge[] = ["corrected", "unconfirmed", "deleted", "trash", "carved", "synced", "duplicate", "other-phone"]

const BADGE_LABEL: Record<RowBadge, string> = {
  corrected: "Corrected",
  unconfirmed: "Not yet confirmed",
  deleted: "Deleted",
  trash: "In trash",
  carved: "Recovered by carving",
  synced: "From another device",
  duplicate: "Found more than once",
  "other-phone": "Also on another phone",
}

const BADGE_TONE: Record<RowBadge, string> = {
  corrected: "text-status-review bg-status-review-soft",
  unconfirmed: "text-status-review bg-status-review-soft",
  deleted: "text-status-deleted bg-status-deleted-soft",
  trash: "text-status-deleted bg-status-deleted-soft",
  carved: "text-status-deleted bg-status-deleted-soft",
  synced: "text-foreground bg-muted",
  duplicate: "text-foreground bg-muted",
  "other-phone": "text-foreground bg-muted",
}

const BADGE_ICON: Partial<Record<RowBadge, ComponentType<{ className?: string; "aria-hidden"?: boolean }>>> = {
  corrected: PencilLine,
  unconfirmed: CircleAlert,
  deleted: Trash2,
  trash: Trash2,
  carved: History,
  synced: Smartphone,
  duplicate: CopyIcon,
}

export function orderBadges(badges: RowBadge[]): RowBadge[] {
  return [...new Set(badges)].sort((a, b) => BADGE_PRIORITY.indexOf(a) - BADGE_PRIORITY.indexOf(b))
}

export function BadgeRow({ badges, max = 2 }: { badges: RowBadge[]; max?: number }) {
  const ordered = orderBadges(badges)
  const shown = ordered.slice(0, max)
  const rest = ordered.slice(max)
  return (
    <span className="inline-flex flex-wrap items-center gap-1">
      {shown.map((b) => {
        const Icon = BADGE_ICON[b]
        const meaning = GLOSSARY_BY_ID[b === "unconfirmed" ? "unconfirmed" : b]?.meaning
        return (
          <span key={b} className={cn("inline-flex items-center gap-1 rounded-sm px-1.5 py-0.5 text-xs font-medium", BADGE_TONE[b])} title={meaning}>
            {Icon && <Icon className="size-3" aria-hidden />}
            {BADGE_LABEL[b]}
          </span>
        )
      })}
      {rest.length > 0 && (
        <span className="rounded-sm bg-muted px-1.5 py-0.5 text-xs font-medium text-foreground" title={rest.map((b) => BADGE_LABEL[b]).join(", ")} aria-label={`${rest.length} more: ${rest.map((b) => BADGE_LABEL[b]).join(", ")}`}>
          +{rest.length}
        </span>
      )}
    </span>
  )
}
